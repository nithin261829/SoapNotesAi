from __future__ import annotations

from datetime import datetime
from typing import Optional

from pydantic import Field

from app.models.common import FirestoreModel, utc_now


class PatientDocument(FirestoreModel):
    """Located at organizations/{orgId}/clinics/{clinicId}/patients/{patientId}/documents/{docId}.

    Metadata for an uploaded patient document (lab report, scan, past record).
    The file itself lives in Cloud Storage at
    organizations/{orgId}/clinics/{clinicId}/patients/{patientId}/documents/{docId}/{filename};
    `storage_path` holds the gs:// URI. Downloads always go through short-lived
    signed URLs generated by the backend — never a public link.
    """

    org_id: str
    clinic_id: str
    patient_id: str
    filename: str
    content_type: str
    size_bytes: int
    storage_path: str  # gs:// URI
    label: Optional[str] = None  # e.g. "Blood report Mar 2026"
    uploaded_by_uid: str
    created_at: datetime = Field(default_factory=utc_now)
